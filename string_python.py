# SINGLE LINE STRING
Name="John Doe"

# Multi-Line String
Address="House No: 4345 \
- Near Millinium Medical Center \
Street Fork \
District Jersey"

print(Name)
print(Address)


# String Is Like Array Each Character Has Index
print(Name[0])
print(Name[1])
print(Name[2])

# Length Of String With Function Called len()
print(len(Address))

# Concatenation Of Strings (Joining Strings)
print(Name+", "+Address)